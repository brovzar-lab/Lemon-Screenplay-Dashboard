function savedLanguage(): UiLanguage {
  if (typeof window === 'undefined') return 'en';
  return window.localStorage.getItem(LANGUAGE_KEY) === 'es' ? 'es' : 'en';
}

void i18n.use(initReactI18next).init({
  lng: savedLanguage(),
  fallbackLng: 'en',
  supportedLngs: ['en', 'es'],
  resources: {
    en: { translation: english },
    es: { translation: spanish },
  },
  interpolation: { escapeValue: false },
  returnNull: false,
});

function applyLanguage(language: string) {
  const resolved: UiLanguage = language === 'es' ? 'es' : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = resolved;
  if (typeof window !== 'undefined') window.localStorage.setItem(languageKey(), resolved);
}

applyLanguage(i18n.language);
i18n.on('languageChanged', applyLanguage);

export function setLanguageUser(uid: string | null): void {
  activeUserId = uid;
  if (typeof window === 'undefined') return;
  const saved = window.localStorage.getItem(languageKey());
  void i18n.changeLanguage(saved === 'es' ? 'es' : 'en');
}

export function currentUiLanguage(): UiLanguage {
  return i18n.resolvedLanguage === 'es' ? 'es' : 'en';
}

